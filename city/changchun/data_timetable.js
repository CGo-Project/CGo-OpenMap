// 录入格式：首班工作日[/周末],夏季末班,冬季末班。
const ccParseRow = (value) => {
    if (!value) return null;
    const [firstValue, summer, winter] = String(value).split(",");
    const [workday, restday] = String(firstValue || "").split("/");
    if (!workday && !restday && !summer && !winter) return null;
    return {
        first: { workday: workday || restday || "", restday: restday || workday || "" },
        summer: summer || "",
        winter: winter || ""
    };
};

const CHANGCHUN_TIMETABLE_DATA = {};
const ccLine = (lineId, firstDestination, firstRows, lastDestination, lastRows) => {
    const line = (typeof linesData !== "undefined" ? linesData : []).find((item) => item?.id === lineId);
    const stationIds = line?.stationIds || [];
    const result = {};
    const append = (rows, destination) => {
        (rows || []).forEach((value, index) => {
            const row = ccParseRow(value);
            const stationId = stationIds[index];
            if (!row || !stationId) return;
            (result[stationId] ||= []).push({ destination, ...row });
        });
    };
    append(firstRows, firstDestination);
    append(lastRows, lastDestination);
    CHANGCHUN_TIMETABLE_DATA[lineId] = result;
};

