/**
 * CGo OpenMap - 兰州地铁「工程名 / 曾用名」资料表 (city/lanzhou/data_station_names.js)
 *
 * ==============================================================================
 * 文件作用 (Overview)
 * ==============================================================================
 * 为兰州线网车站提供「工程名」（建设期工程暂用名 / 拟定名）与「曾用名」
 * （历史正式站名，含更名前的旧称）两份资料，由车站卡片「车站信息」选项卡中的
 * 模块 city/lanzhou/modules/lanzhou_station_names.js **只读**展示。
 *
 * 卡片中按资料逐行展示：「工程名」一行、「曾用名」一行，两行各自独立、绝不合并。
 * 没有工程名或曾用名的车站，对应行不显示；两项都没有的车站，「车站信息」里整块不显示。
 * 前端不提供任何编辑入口与显示开关，资料与显隐一律在本文件（数据层）维护。
 *
 * ==============================================================================
 * 如何填写 (How to edit)
 * ==============================================================================
 * 在下方 stations 中，以「车站 ID」为键添加条目即可；没有资料的车站直接不写，
 * 或只写有的那一项（另一项留空即不显示该行）。示例：
 *
 *     stations: {
 *         "M107": { engineering: "东方红广场", former: "广场" },
 *         "M118": { engineering: ["兰州城市学院", "省科技馆"], former: "兰州城市学院" },
 *         "M119": { engineering: { value: "奥体中心", visible: false }, former: "崔家大滩" }
 *     }
 *
 * 字段取值支持以下三种写法（engineering 与 former 各自独立）：
 *   1. 字符串：            "东方红广场"
 *   2. 字符串数组：        ["旧名一", "旧名二"]     → 展示为「旧名一、旧名二」
 *   3. 对象：              { value: "文本", visible: false }
 *        value   —— 展示文本（亦可写成 text / name）
 *        visible —— 该行是否展示；false 表示「有资料但不展示该行」
 *                   等价写法：show: false / hidden: true / enabled: false
 *
 * 站点级总开关（可选，写在条目内）：
 *       { hidden: true }        → 该站「工程名」「曾用名」两行都不展示
 *
 * ==============================================================================
 * 显示与隐藏（全部在数据层） (Visibility control)
 * ==============================================================================
 *   A. 全局总开关：LANZHOU_STATION_NAMES.enabled = false
 *                  → 兰州全部车站均不展示该模块；
 *   B. 模块开关：  city/lanzhou/lanzhou.js 中
 *                  stationBoard.modules["lanzhou-station-names"].enabled = false
 *                  → 由核心引擎直接屏蔽该模块；
 *   C. 逐行开关：  每个车站的 engineering / former 各自带 visible 标记，互不影响；
 *   D. 整站开关：  条目内写 { hidden: true }。
 *
 * ==============================================================================
 * 逐站优先级 (Priority, 命中即停)
 * ==============================================================================
 *   1. data_stations.js 中车站对象自带字段：
 *        engineeringName / engineering
 *        formerName / formerNames / former / oldName
 *   2. 本文件 stations[车站ID] 的对应字段
 *
 * ==============================================================================
 * 数据说明 (Data note)
 * ==============================================================================
 * 现有资料来自官方公布的建设期工程站名与站名沿革（2026-09 录入，共 13 站）；
 * 其余车站不写条目即自动不显示，后续新增站点按同一格式补充即可。
 * ==============================================================================
 */

